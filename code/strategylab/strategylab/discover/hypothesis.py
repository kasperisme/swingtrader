"""The hypothesis grammar — a finite, enumerable space of testable claims.

A hypothesis here is not free-form. It is a tuple of (signal primitive,
transform, outcome, horizon), which buys three things a free-form proposer
cannot:

  * **It can be exhausted.** The loop can report "the space is covered" rather
    than running forever, which is what makes a null terminal.
  * **It can be deduplicated.** The same claim arriving twice under different
    words would inflate the trial count while adding no information — or worse,
    be counted as an independent confirmation.
  * **It can be hashed.** The trial count that sets the significance bar is only
    meaningful if the thing being counted is well defined.

The primitives are the features this project already computes. The transforms
are the handful of ways a practitioner actually reshapes one: use it as-is,
invert it, difference it over a window, or measure it against its own recent
level. Nothing here is exotic, and that is intentional — the space is meant to
cover the plausible, not the ingenious.
"""

from __future__ import annotations

import hashlib
import itertools
from dataclasses import dataclass, field

import numpy as np

